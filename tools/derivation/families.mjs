// Word families: the derived words and compounds the language builds from a base, written once in tools/derivation/families.txt.
//   node tools/derivation/families.mjs        writes tools/lexicon/13-families.txt (the dictionary entries that do not exist yet)
//   node tools/lexicon/build.mjs              merges them into data/vocabulary.json
//   node tools/derivation/build.mjs           writes data/derivations.json (the pairs, from the rules, this file and the exceptions)
// Format of families.txt (see the file): "base: type derived, [pos:]type derived" and "a + b => compound".
import fs from 'node:fs';
const here = new URL('./', import.meta.url), root = new URL('../../', import.meta.url);

export const TYPES = ['agent', 'act', 'result', 'quality', 'abstract', 'place', 'diminutive', 'feminine', 'adjective', 'privative', 'adverb', 'causative', 'negative', 'repetitive', 'excess'];
const POSMAP = { n: 'noun', v: 'verb', a: 'adjective', adv: 'adverb' };
const DEFAULT_POS = { agent: 'noun', act: 'noun', result: 'noun', quality: 'noun', abstract: 'noun', place: 'noun', diminutive: 'noun', feminine: 'noun', adjective: 'adjective', privative: 'adjective', adverb: 'adverb', causative: 'verb' };

const norm = s => s.toLowerCase().trim();
export const loadVocabulary = () => JSON.parse(fs.readFileSync(new URL('data/vocabulary.json', root), 'utf8')).vocabulary;

// "v:bake" / "stable" -> { pos, lemma }
const token = t => { const m = t.trim().match(/^(n|v|a|adv):\s*(.+)$/); return m ? { pos: POSMAP[m[1]], lemma: m[2].trim() } : { pos: null, lemma: t.trim() }; };

export function findEntry(vocabulary, tok, order = ['noun', 'verb', 'adjective', 'adverb']) {
    const hits = vocabulary.filter(e => norm(e.lemma) === norm(tok.lemma) && !e.gloss && (tok.pos ? e.pos === tok.pos : order.includes(e.pos)));
    return tok.pos ? hits[0] : order.map(p => hits.find(e => e.pos === p)).find(Boolean);
}

// -> { pairs: [{ type, derived: {pos, lemma}, bases: [{pos, lemma}], base line }], errors }
export function parseFamilies(text) {
    const pairs = [], errors = [];
    text.split('\n').forEach((raw, i) => {
        const line = raw.replace(/#.*$/, '').trim();
        if (!line) return;
        const where = `families.txt:${i + 1}`;
        const comp = line.includes(' + ') ? line.match(/^(.+?)\s+\+\s+(.+?)(?:\s*=>\s*(.+))?$/) : null;
        if (comp) {
            const mod = token(comp[1]), head = token(comp[2]);
            pairs.push({ type: 'compound', derived: { pos: 'noun', lemma: comp[3]?.trim() ?? `${mod.lemma} ${head.lemma}` }, bases: [mod, head], where });
            return;
        }
        const m = line.match(/^((?:(?:n|v|a|adv):)?[^:]+?):\s*(.+)$/);
        if (!m) { errors.push(`${where}: cannot read "${line}"`); return; }
        const base = token(m[1]);
        for (const spec of m[2].split(',').map(x => x.trim()).filter(Boolean)) {
            const s = spec.match(/^(?:(n|v|a|adv):)?(\w+)\s+(.+)$/);
            if (!s || !TYPES.includes(s[2]) ) { errors.push(`${where}: cannot read "${spec}"`); continue; }
            pairs.push({ type: s[2], derived: { pos: s[1] ? POSMAP[s[1]] : null, lemma: s[3].trim() }, bases: [base], where });
        }
    });
    return { pairs, errors };
}

// Resolves the pairs against a vocabulary: default parts of speech, existing entries, entries to create.
export function resolveFamilies(vocabulary, pairs) {
    const errors = [], resolved = [];
    for (const p of pairs) {
        const bases = p.bases.map(b => findEntry(vocabulary, b));
        if (bases.some(b => !b)) { errors.push(`${p.where}: unknown base ${p.bases.filter((b, i) => !bases[i]).map(b => b.lemma).join(', ')}`); continue; }
        const pos = p.derived.pos ?? DEFAULT_POS[p.type] ?? bases[0].pos;
        const existing = vocabulary.find(e => norm(e.lemma) === norm(p.derived.lemma) && e.pos === pos && !e.gloss);
        resolved.push({ ...p, pos, bases, existing });
    }
    return { resolved, errors };
}

const slug = s => norm(s).replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const POSDSL = { noun: '', verb: 'v:', adjective: 'a:', adverb: 'adv:' };

if (process.argv[1]?.endsWith('families.mjs')) {
    const vocabulary = loadVocabulary();
    const { pairs, errors: e1 } = parseFamilies(fs.readFileSync(new URL('families.txt', here), 'utf8'));
    const { resolved, errors: e2 } = resolveFamilies(vocabulary, pairs);
    const errors = [...e1, ...e2];
    if (errors.length) { console.error(errors.join('\n')); console.error(`${errors.length} problems; nothing written`); process.exit(1); }
    // new entries inherit the domain, era, culture and biome of their base; groups share them
    const animacyOf = (r, base) => (['agent', 'feminine'].includes(r.type) ? 'human' : r.type === 'diminutive' ? (base.features?.animacy ?? 'inanimate') : 'inanimate');
    const lines = ['# GENERATED by tools/derivation/families.mjs from tools/derivation/families.txt. Do not edit.', '@tier domain', '@era', '@culture', '@biome', '@tags'];
    const groups = new Map();
    for (const r of resolved) {
        if (r.existing && !(r.existing.tags ?? []).includes('derived')) continue;
        const base = r.bases[r.bases.length - 1];
        const animacy = r.pos === 'noun' ? animacyOf(r, base) : 'inanimate';
        const key = [base.domain, (base.era ?? []).join(','), (base.culture ?? []).join(','), (base.biome ?? []).join(','), animacy].join('|');
        if (!groups.has(key)) groups.set(key, { base, animacy, items: [] });
        groups.get(key).items.push(r);
    }
    let count = 0;
    for (const { base, animacy, items } of [...groups.values()].sort((a, b) => a.base.domain.localeCompare(b.base.domain))) {
        const opts = ['tags=derived', base.era?.length ? `era=${base.era.join(',')}` : null, base.culture?.length ? `culture=${base.culture.join(',')}` : null, base.biome?.length ? `biome=${base.biome.join(',')}` : null, `animacy=${animacy}`].filter(Boolean);
        lines.push('', `@domain ${base.domain}`, `## derived_${base.domain}_${++count} | ${opts.join(' | ')}`);
        lines.push([...new Set(items.map(r => `${POSDSL[r.pos]}${r.derived.lemma}`))].join(', '));
    }
    fs.writeFileSync(new URL('tools/lexicon/13-families.txt', root), lines.join('\n') + '\n');
    console.log(`${resolved.length} pairs, ${resolved.filter(r => !r.existing || (r.existing.tags ?? []).includes('derived')).length} entries -> tools/lexicon/13-families.txt`);
}
