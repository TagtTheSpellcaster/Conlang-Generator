# Generates data/sentence-templates.json (hand-edit the JSON afterwards if you prefer).
import json
I,YOU,YOU_O,WE,THEY,ME='pronoun.first_person_singular','pronoun.second_person_singular','pronoun.second_person_singular_object','pronoun.first_person_plural','pronoun.third_person_plural','pronoun.first_person_singular_object'
MY,YOUR,THIS,THAT='my:determiner','your:determiner','demonstrative.this','demonstrative.that'
n=lambda w:w+':noun'; v=lambda w:w+':verb'; a=lambda w:w+':adjective'; adv=lambda w:w+':adverb'
def NP(head,**k): 
    d={'head':head}; d.update(k); return d
def VP(head,**k):
    d={'head':head}; d.update(k); return d
def PP(adp,case,np): return {'adp':adp+':adposition','case':case,'np':np}
T=[]
def add(en,**parts): T.append({'id':f't{len(T)+1:02d}','en':en,**parts})
KIN=[n('friend'),n('sister'),n('father')]
add('I am your [friend|sister|father].',S=NP(I),V=VP(v('be')),O=NP(KIN,poss=YOUR))
add('You are my [friend|sister|father].',S=NP(YOU),V=VP(v('be')),O=NP(KIN,poss=MY))
add('This is [water|food|bread].',S=NP(THIS),V=VP(v('be')),O=NP([n('water'),n('food'),n('bread')]))
add('That is a [sword|house|tree].',S=NP(THAT),V=VP(v('be')),O=NP([n('sword'),n('house'),n('tree')],det='indefinite'))
add('We are here.',S=NP(WE),V=VP(v('be')),O=NP(adv('here')))
add('They are there.',S=NP(THEY),V=VP(v('be')),O=NP(adv('there')))
add('I have [water|food|bread].',S=NP(I),V=VP(v('have')),O=NP([n('water'),n('food'),n('bread')]))
add('You have [water|food|bread].',S=NP(YOU),V=VP(v('have')),O=NP([n('water'),n('food'),n('bread')]))
add('The sun is [hot|bright].',S=NP(n('sun'),det='definite'),V=VP(v('be')),O=NP([a('hot'),a('bright')]))
add('The stone is [hot|cold].',S=NP(n('stone'),det='definite'),V=VP(v('be')),O=NP([a('hot'),a('cold')]))
add('The moon is [bright|dark].',S=NP(n('moon'),det='definite'),V=VP(v('be')),O=NP([a('bright'),a('dark')]))
add('I eat [food|bread].',S=NP(I),V=VP(v('eat')),O=NP([n('food'),n('bread')]))
add('The [wolf|dog] drinks [water|milk].',S=NP([n('wolf'),n('dog')],det='definite'),V=VP(v('drink')),O=NP([n('water'),n('milk')]))
add('I see you.',S=NP(I),V=VP(v('see')),O=NP(YOU_O))
add('You see me.',S=NP(YOU),V=VP(v('see')),O=NP(ME))
add('The hunter [kills|hunts] the wolf.',S=NP(n('hunter'),det='definite'),V=VP([v('kill'),v('hunt')]),O=NP(n('wolf'),det='definite'))
add('I [love|trust|help] you.',S=NP(I),V=VP([v('love'),v('trust'),v('help')]),O=NP(YOU_O))
add('I fear the [sword|enemy].',S=NP(I),V=VP(v('fear')),O=NP([n('sword'),n('enemy')],det='definite'))
add('I go to the [village|city|forest].',S=NP(I),V=VP(v('go')),O=PP('to','dative',NP([n('village'),n('city'),n('forest')],det='definite')))
add('You come from the [village|city].',S=NP(YOU),V=VP(v('come')),O=PP('from','ablative',NP([n('village'),n('city')],det='definite')))
add('The sun rises.',S=NP(n('sun'),det='definite'),V=VP(v('rise')))
add('The stone falls.',S=NP(n('stone'),det='definite'),V=VP(v('fall')))
add('The [bird|fish] moves [up|down].',S=NP([n('bird'),n('fish')],det='definite'),V=VP(v('move')),O=NP([adv('up'),adv('down')]))
add('The wolf walks in the forest.',S=NP(n('wolf'),det='definite'),V=VP(v('walk')),O=PP('in','locative',NP(n('forest'),det='definite')))
add('Stay here.',mood='imperative',seq=['V','O'],V=VP(v('stay')),O=NP(adv('here')))
add('Come with me.',mood='imperative',seq=['V','O'],V=VP(v('come')),O=PP('with','instrumental',NP(ME)))
add('Who are you?',seq=['initial','V','S'],initial=[NP('interrogative.who')],V=VP(v('be')),S=NP(YOU))
add('What is this?',seq=['initial','V','S'],initial=[NP('interrogative.what')],V=VP(v('be')),S=NP(THIS))
add('Where are we?',seq=['initial','V','S'],initial=[NP(adv('where'))],V=VP(v('be')),S=NP(WE))
add('When do you go?',seq=['initial','S','V'],initial=[NP('when:conjunction')],S=NP(YOU),V=VP(v('go')))
add('Why do you do this?',seq=['initial','S','V','O'],initial=[NP(adv('why'))],S=NP(YOU),V=VP(v('do')),O=NP(THIS))
add('How does this work?',seq=['initial','S','V'],initial=[NP(adv('how'))],S=NP(THIS),V=VP(v('work')))
add('Where is the water?',seq=['initial','V','S'],initial=[NP(adv('where'))],V=VP(v('be')),S=NP(n('water'),det='definite'))
add('I do not want this.',S=NP(I),V=VP(v('want'),neg=True),O=NP(THIS))
add('You cannot enter.',S=NP(YOU),V=VP(v('enter'),neg=True,aux='can:particle'))
add('I do not know.',S=NP(I),V=VP(v('know'),neg=True))
add('I know the way.',S=NP(I),V=VP(v('know')),O=NP(n('way'),det='definite'))
add('I can help you.',S=NP(I),V=VP(v('help'),aux='can:particle'),O=NP(YOU_O))
add('Do not touch this.',mood='imperative',seq=['V','O'],V=VP(v('touch'),neg=True),O=NP(THIS))
add('I am hungry.',S=NP(I),V=VP(v('be')),O=NP(a('hungry')))
add('My hand hurts.',S=NP(n('hand'),poss=MY),V=VP(v('hurt')))
add('I want to sleep.',S=NP(I),V=VP(v('want')),O=NP(v('sleep')))
add('This is [much|little].',S=NP(THIS),V=VP(v('be')),O=NP(['much:determiner','little:determiner']))
add('Everything is ready.',S=NP('everything:pronoun'),V=VP(v('be')),O=NP(a('ready')))
add('Nothing exists.',S=NP('nothing:pronoun'),V=VP(v('exist')))
add('Today we work.',seq=['initial','S','V'],initial=[NP(n('today'))],S=NP(WE),V=VP(v('work')))
add('Tomorrow we travel.',tense='future',seq=['initial','S','V'],initial=[NP(n('tomorrow'))],S=NP(WE),V=VP(v('travel')))
add('Yesterday the hunter came.',tense='past',seq=['initial','S','V'],initial=[NP(n('yesterday'))],S=NP(n('hunter'),det='definite'),V=VP(v('come')))
add('The [dog|wolf|horse] sees the [hunter|farmer].',S=NP([n('dog'),n('wolf'),n('horse')],det='definite'),V=VP(v('see')),O=NP([n('hunter'),n('farmer')],det='definite'))
add('I [eat|drink] [food|water].',S=NP(I),V=VP([v('eat'),v('drink')]),O=NP([n('food'),n('water')]))
add('The [hunter|farmer] has [food|water].',S=NP([n('hunter'),n('farmer')],det='definite'),V=VP(v('have')),O=NP([n('food'),n('water')]))
add('I see the [house|village].',S=NP(I),V=VP(v('see')),O=NP([n('house'),n('village')],det='definite'))
add('We build a [house|boat].',S=NP(WE),V=VP(v('build')),O=NP([n('house'),n('boat')],det='indefinite'))
add('The bird is [small|large].',S=NP(n('bird'),det='definite'),V=VP(v('be')),O=NP([a('small'),a('large')]))
add('The fish is [small|large].',S=NP(n('fish'),det='definite'),V=VP(v('be')),O=NP([a('small'),a('large')]))
# added: they exercise adjective position, agreement, number and gender
add('I see the [small|large] house.',S=NP(I),V=VP(v('see')),O=NP(n('house'),det='definite',adj=[a('small'),a('large')]))
add('The good wolf sees the [small|large] dog.',S=NP(n('wolf'),det='definite',adj=a('good')),V=VP(v('see')),O=NP(n('dog'),det='definite',adj=[a('small'),a('large')]))
add('My sister is good.',S=NP(n('sister'),poss=MY),V=VP(v('be')),O=NP(a('good')))
add('My father is good.',S=NP(n('father'),poss=MY),V=VP(v('be')),O=NP(a('good')))
add('The wolves see the hunters.',requires={'number':'plural'},S=NP(n('wolf'),det='definite',number='plural'),V=VP(v('see')),O=NP(n('hunter'),det='definite',number='plural'))
add('We see two horses.',requires={'number':'dual'},S=NP(WE),V=VP(v('see')),O=NP(n('horse'),number='dual'))
json.dump({'version':1,'templates':T},open('data/sentence-templates.json','w'),indent=1,ensure_ascii=False)
print(len(T))
